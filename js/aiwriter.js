  function polish(text) {
    let t = String(text || '').replace(/\r\n?/g, '\n');
    const map = [
      [/然后然后/g, '然后'], [/就是就是/g, '就是'], [/这个这个/g, '这个'],
      [/特别特别/g, '格外'], [/非常非常/g, '十分'], [/好多好多/g, '许多'],
      [/我觉得吧[，,]?/g, '我认为'], [/反正/g, '总体来看'], [/搞/g, '做'],
      [/弄/g, '处理'], [/挺/g, '颇为'], [/啥/g, '什么'], [/咋/g, '怎么'],
      [/一下子/g, '随即'], [/有点儿/g, '略显'], [/东西/g, '内容'],
      [/其实吧[，,]?/g, '事实上，'], [/所以说/g, '因此'], [/然后呢[，,]?/g, '随后，'],
      [/[，,]{2,}/g, '，'], [/[。.]{2,}/g, '。'], [/ {2,}/g, ' '],
      [/\n{3,}/g, '\n\n']
    ];
    map.forEach(function (p) { t = t.replace(p[0], p[1]); });
    // 段落末尾补句号、长段自动断句
    t = t.split('\n').map(function (line) {
      line = line.trim();
      if (!line) return '';
      if (!/[。！？；：.!?;:”’】）]$/.test(line)) line += '。';
      if (line.length > 90) {
        const parts = line.split(/(?<=[。！？；])/);
        let acc = '', out = [];
        parts.forEach(function (p) {
          if ((acc + p).length > 62 && acc) { out.push(acc); acc = p; } else acc += p;
        });
        if (acc) out.push(acc);
        return out.join('\n');
      }
      return line;
    }).join('\n');
    return t.trim();
  }

  function generate(topic, subject, words) {
    const bank = BANK[topic] || BANK.zuowen;
    subject = (subject || '').trim();
    const target = Math.max(120, Math.min(3000, words || 600));
    const paras = [];
    let head = bank.open[0];
    if (subject) head = '关于「' + subject + '」，' + head.charAt(0).toLowerCase() + head.slice(1);
    paras.push(head);

    let idx = 0, guard = 0;
    const connectors = ['说到这里，还有一层意思需要补上。', '顺着这个往下想，', '换个角度看，', '再往后一点，', '与此相关的是，', '这里不妨多写一句：', '回过头来看，'];
    while (paras.join('').length < target * 0.86 && guard < 120) {
      let s = bank.body[idx % bank.body.length];
      if (idx > 0 && idx % 3 === 0) s = connectors[(idx / 3) % connectors.length | 0] + s;
      if (subject && guard % 5 === 2) s += '这也让我重新想起「' + subject + '」这个题目本身的分量。';
      paras.push(s);
      if (idx % 4 === 3) paras.push('');
      idx++; guard++;
    }
    bank.end.forEach(function (e) { paras.push(e); });
    let out = paras.join('\n').replace(/\n{3,}/g, '\n\n');
    return out;
  }

  function continueText(text, words) {
    const tail = String(text || '').slice(-160);
    const topic = /总结|工作|项目/.test(tail) ? 'zongjie' : (/读书|书|笔记/.test(tail) ? 'dushu' : 'riji');
    const extra = generate(topic, '', Math.max(150, (words || 300) * 0.6));
    return String(text || '').trimEnd() + '\n\n' + extra.split('\n').slice(1).join('\n');
  }

  async function apiGenerate(cfg, prompt, onProgress) {
    if (!cfg || !cfg.url || !cfg.key) throw new Error('未配置 API');
    if (onProgress) onProgress('正在调用大模型…', 20);
    const res = await fetch(cfg.url.replace(/\/$/, '') + '/chat/completions', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Authorization': 'Bearer ' + cfg.key },
      body: JSON.stringify({
        model: cfg.model || 'gpt-3.5-turbo',
        messages: [
          { role: 'system', content: '你是中文写作助手。只输出正文，不要标题、不要解释、不要markdown标记，段落之间用换行分隔，语言自然口语化，适合作为手写稿内容。' },
          { role: 'user', content: prompt }
        ],
        temperature: 0.8
      })
    });
    if (!res.ok) throw new Error('接口返回 ' + res.status);
    const j = await res.json();
    const t = j && j.choices && j.choices[0] && j.choices[0].message && j.choices[0].message.content;
    if (!t) throw new Error('接口未返回正文');
    return t.trim();
  }

